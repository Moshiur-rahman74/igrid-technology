export const getProductsByCategory = (category: string): Product[] => {
  return products.filter(product => product.category === category);
};

export const getProductsByBrand = (brand: string): Product[] => {
  return products.filter(product => product.brand === brand);
};

export const getProductById = (id: string): Product | undefined => {
  return products.find(product => product.id === id);
};

export const getProductsByBudgetLevel = (budgetLevel: string): Product[] => {
  return products.filter(product => product.budgetLevel === budgetLevel);
};

export const getInStockProducts = (): Product[] => {
  return products.filter(product => product.stockStatus === 'In Stock');
};
